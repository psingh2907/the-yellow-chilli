/**
 * The Satna menu, transcribed from the restaurant's Zomato listing
 * (October 2026). Prices are Zomato's and may differ slightly for dine-in.
 * Obvious duplicates and spelling slips on the listing were tidied up.
 *
 * `heat` is our own guide for the Spice-o-meter, not the kitchen's:
 * 0 mild · 1 medium · 2 hot · 3 fiery.
 */
export type Diet = "veg" | "egg" | "nonveg";
export type Heat = 0 | 1 | 2 | 3;

export interface MenuItem {
  name: string;
  price: number;
  diet: Diet;
  heat: Heat;
  note?: string;
  signature?: boolean;
}

export interface MenuCategory {
  id: string;
  title: string;
  blurb: string;
  items: MenuItem[];
}

